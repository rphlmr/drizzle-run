// Generate what core needs from the guest packages: `node scripts/guests/generate.ts [--check]`.
//
// Stage 1 reads only guests/*/, their installs and packages/runtime/package.json, never packages/core/src/registry,
// because core's registry is built on the catalog this stage writes. It installs the guests into the cache first
// (`pnpm guests:install`), reusing an unchanged install, to read each drizzle-orm exports map.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { createGuestPackageLocator } from "./guest-installs.ts";
import { ORM_EXPORT_INVENTORY_INTERFACE, readOrmExportInventory } from "./orm-export-inventory.ts";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const guestsDir = join(rootDir, "guests");
const runtimeManifestPath = join(rootDir, "packages/runtime/package.json");
const guestCatalogPath = join(rootDir, "packages/core/src/releases/guest-catalog.generated.ts");
const hostEngineNames = ["@electric-sql/pglite", "@sqlite.org/sqlite-wasm"];

/**
 * Render the guest catalog
 *
 * One entry per guest image, sorted by id, with the pair fields of its slim guest, its exact package pins and its
 * editor-only `devPackages` (the types the editor loads, never in the image); the
 * release pairs grouped from them; the drizzle-orm subpaths each pinned version exports; and the host-side database
 * engines the runtime package depends on. The output depends only on those files and installs.
 */
export async function renderGuestCatalog() {
  const [locator, runtimeManifest] = await Promise.all([
    createGuestPackageLocator(guestsDir),
    readFile(runtimeManifestPath, "utf8").then(JSON.parse),
  ]);
  const guestPackages = locator.guests;
  const ormExportInventory = await readOrmExportInventory(locator);
  const guestImages = Object.fromEntries(
    guestPackages.map((guest) => [
      guest.id,
      {
        pairId: guest.pairId,
        releaseLine: guest.releaseLine,
        recommended: guest.recommended,
        guestFlavor: guest.guestFlavor,
        ormVersion: guest.ormVersion,
        kitVersion: guest.kitVersion,
        ormApi: guest.ormApi,
        kitApi: guest.kitApi,
        packages: guest.dependencies,
        devPackages: guest.devDependencies,
        lockDigest: guest.lockDigest,
      },
    ]),
  );
  // Emitted as a literal so core keeps its exact pair types; grouping at runtime would widen them to string keys.
  const releasePairs = Object.fromEntries(
    guestPackages
      .filter((guest) => guest.guestFlavor === "slim")
      .map((slim) => [
        slim.pairId,
        {
          releaseLine: slim.releaseLine,
          ormVersion: slim.ormVersion,
          kitVersion: slim.kitVersion,
          recommended: slim.recommended,
          // Guests are sorted by id, so the slim image (the plain pair id) comes first.
          guestFlavors: guestPackages.filter((guest) => guest.pairId === slim.pairId).map((guest) => guest.guestFlavor),
        },
      ]),
  );
  const hostEngines = Object.fromEntries(
    hostEngineNames.map((name) => {
      const version = runtimeManifest.dependencies?.[name];

      if (version === undefined) {
        throw new Error(`packages/runtime/package.json must depend on the host engine ${name}`);
      }

      return [name, version];
    }),
  );

  return [
    "// Generated by scripts/guests/generate.ts from guests/*/ and packages/runtime/package.json. Do not edit.",
    "",
    "/** One entry per guest image (release pair and flavor); pair fields are copied from the pair's slim guest. */",
    `export const GUEST_IMAGES = ${JSON.stringify(guestImages, null, 2)} as const;`,
    "",
    "/**",
    " * Supported ORM and Kit release pairs, grouped from the guest images",
    " *",
    " * Legacy keeps exactly one pair: a fix release updates its versions in place, and manifests on an older Legacy",
    " * version follow it without asking. Next adds a pair per release; removing one asks its projects to choose another.",
    " * `guestFlavors` lists the guest images the pair ships, slim first.",
    " */",
    `export const RELEASE_PAIRS = ${JSON.stringify(releasePairs, null, 2)} as const;`,
    "",
    "/** The drizzle-orm subpaths user code may import, by family, read from each pinned version's exports map. */",
    ORM_EXPORT_INVENTORY_INTERFACE,
    "",
    "/** The export inventory of each pinned drizzle-orm version, keyed by version. */",
    `export const ORM_EXPORT_INVENTORY = ${JSON.stringify(ormExportInventory, null, 2)} as const satisfies Readonly<Record<string, OrmExportInventory>>;`,
    "",
    "/** Host-side database engines, read from packages/runtime/package.json dependencies. */",
    `export const HOST_ENGINES = ${JSON.stringify(hostEngines, null, 2)} as const;`,
    "",
  ].join("\n");
}

async function readCommitted(path: string) {
  try {
    return await readFile(path, "utf8");
  } catch (cause) {
    if (cause instanceof Error && "code" in cause && cause.code === "ENOENT") {
      return null;
    }

    throw cause;
  }
}

async function main(args: string[]) {
  const checkOnly = args.includes("--check");
  const contents = await renderGuestCatalog();
  const committed = await readCommitted(guestCatalogPath);
  const displayPath = relative(rootDir, guestCatalogPath);

  if (committed === contents) {
    console.log(`${displayPath} is current.`);
    return;
  }

  if (checkOnly) {
    console.error(`${displayPath} is stale. Run pnpm guests:generate and commit the result.`);
    process.exitCode = 1;
    return;
  }

  await writeFile(guestCatalogPath, contents);
  console.log(`Wrote ${displayPath}.`);
}

if (import.meta.main) {
  await main(process.argv.slice(2));
}
