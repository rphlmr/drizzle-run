// Writes worker/examples.generated.ts. With --check, fails when the file is stale.
import { readdir, readFile, writeFile } from "node:fs/promises";

const check = process.argv.includes("--check");
const examplesRoot = new URL("../examples/", import.meta.url);
const output = new URL("../worker/examples.generated.ts", import.meta.url);
const summaries = [];
const dialects = ["postgresql", "sqlite"];
const guestFlavors = ["slim", "effect"];

interface ExampleSide {
  dialect?: string;
  releasePair?: string;
  guestFlavor?: string;
}

interface ExampleMetadata extends ExampleSide {
  slug: string;
  status: string;
  title: string;
  description: string;
  sides?: ExampleSide[];
}

/** The ORM version of an `orm-<version>__kit-<version>` release pair; undefined for anything else. */
function readOrmVersion(releasePair: string | undefined) {
  return typeof releasePair === "string" ? /^orm-(.+)__kit-.+$/.exec(releasePair)?.[1] : undefined;
}

/**
 * What one side runs, or the one version: its own dialect, releasePair and guestFlavor, else the example's, as
 * src/examples/catalog.ts reads them
 */
function readSide(folder: string, example: ExampleSide, side: ExampleSide = {}) {
  const dialect = side.dialect ?? example.dialect;
  const ormVersion = readOrmVersion(side.releasePair ?? example.releasePair);
  const guestFlavor = side.guestFlavor ?? example.guestFlavor ?? "slim";

  if (
    dialect === undefined ||
    !dialects.includes(dialect) ||
    ormVersion === undefined ||
    !guestFlavors.includes(guestFlavor)
  ) {
    throw new Error(
      `Expected examples/${folder}/example.json to give each side a dialect, an orm-*__kit-* releasePair and a known guestFlavor.`,
    );
  }

  return { dialect, ormVersion, guestFlavor };
}

for (const entry of (await readdir(examplesRoot, { withFileTypes: true })).toSorted((left, right) =>
  left.name.localeCompare(right.name),
)) {
  if (!entry.isDirectory()) {
    continue;
  }

  const metadataPath = new URL(`${entry.name}/example.json`, examplesRoot);
  const example: ExampleMetadata = JSON.parse(await readFile(metadataPath, "utf8"));
  const { slug, status, title, description } = example;

  if (typeof slug !== "string" || !["published", "draft", "deleted"].includes(status)) {
    throw new Error(
      `Expected examples/${entry.name}/example.json to have a text slug and a published, draft or deleted status.`,
    );
  }

  if (status !== "published") {
    continue;
  }

  if (typeof title !== "string" || typeof description !== "string") {
    throw new Error(`Expected examples/${entry.name}/example.json to have a text title and description.`);
  }

  const sides = Array.isArray(example.sides)
    ? example.sides.map((side) => readSide(entry.name, example, side))
    : [readSide(entry.name, example)];

  summaries.push({ slug, title, description, sides });
}

const source = `// Generated by scripts/build-example-index.ts from examples/*/example.json. Do not edit.

/** What one side of an official example runs, or its one version: its database, ORM version and guest flavor. */
export interface ExampleSideSummary {
  readonly dialect: "postgresql" | "sqlite";
  readonly ormVersion: string;
  readonly guestFlavor: "slim" | "effect";
}

/** An official example's slug, title, description, and sides, as its \`example.json\` states them. */
export interface ExampleSummary {
  readonly slug: string;
  readonly title: string;
  readonly description: string;
  /** One side for a one-version example, two in side order for a side-by-side one. */
  readonly sides: readonly [ExampleSideSummary] | readonly [ExampleSideSummary, ExampleSideSummary];
}

/** Every published example, by slug. */
export const exampleSummaries: readonly ExampleSummary[] = ${JSON.stringify(summaries, null, 2)};
`;
const current = await readFile(output, "utf8").catch(() => undefined);

if (current !== source) {
  if (check) {
    console.error("Stale worker/examples.generated.ts, run `pnpm --filter @drizzle-run/app generate:examples`.");
    process.exit(1);
  }

  await writeFile(output, source);
  console.log("wrote worker/examples.generated.ts");
}
